# Build-only tools: end users need a Vulkan-capable driver, not these downloads.
[CmdletBinding()]
param(
    [string]$CacheDirectory
)

$ErrorActionPreference = 'Stop'
if (!$CacheDirectory) {
    $CacheDirectory = Join-Path $PSScriptRoot '..\build-tools\vulkan'
}
$ProgressPreference = 'SilentlyContinue'
[Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
$CacheDirectory = [IO.Path]::GetFullPath($CacheDirectory)
New-Item -ItemType Directory -Force -Path $CacheDirectory | Out-Null

function Get-PinnedArchive {
    param([string]$Name, [string]$Url, [string]$Sha256, [string]$ExpectedFile)

    $archive = Join-Path $CacheDirectory "$Name.zip"
    if (!(Test-Path -LiteralPath $archive)) {
        Write-Host "Downloading Vulkan build tool: $Name"
        $download = "$archive.download"
        Invoke-WebRequest -UseBasicParsing -Uri $Url -OutFile $download
        if ((Get-FileHash -LiteralPath $download -Algorithm SHA256).Hash -ne $Sha256) {
            throw "SHA-256 mismatch for $Url. The download was not extracted."
        }
        Move-Item -LiteralPath $download -Destination $archive -Force
    }
    if ((Get-FileHash -LiteralPath $archive -Algorithm SHA256).Hash -ne $Sha256) {
        throw "SHA-256 mismatch for cached archive $archive. Remove this file and retry."
    }

    $directory = Join-Path $CacheDirectory $Name
    $marker = Join-Path $directory '.sha256'
    $expected = Join-Path $directory $ExpectedFile
    if (!(Test-Path -LiteralPath $expected) -or !(Test-Path -LiteralPath $marker) -or
        (Get-Content -LiteralPath $marker -Raw).Trim() -ne $Sha256) {
        Expand-Archive -LiteralPath $archive -DestinationPath $directory -Force
        if (!(Test-Path -LiteralPath $expected)) {
            throw "Vulkan build tool archive is missing $ExpectedFile"
        }
        Set-Content -LiteralPath $marker -Value $Sha256 -Encoding ASCII
    }
    return $directory
}

$include = $null
$compiler = $null
if ($env:VULKAN_SDK) {
    $sdkInclude = Join-Path $env:VULKAN_SDK 'Include'
    if (Test-Path -LiteralPath (Join-Path $sdkInclude 'vulkan\vulkan_core.h')) {
        foreach ($name in @('glslangValidator.exe', 'glslang.exe')) {
            $candidate = Join-Path $env:VULKAN_SDK "Bin\$name"
            if (Test-Path -LiteralPath $candidate) {
                $include = [IO.Path]::GetFullPath($sdkInclude)
                $compiler = [IO.Path]::GetFullPath($candidate)
                break
            }
        }
    }
}

if (!$compiler) {
    # These are the same Khronos releases used for the validated Vulkan prototypes.
    $headers = Get-PinnedArchive 'headers-1.3.290' `
        'https://github.com/KhronosGroup/Vulkan-Headers/archive/refs/tags/v1.3.290.zip' `
        '918a8bb31b8312fd649fd1d1826443da870f33f3187c16c4528aa94927409bab' `
        'Vulkan-Headers-1.3.290\include\vulkan\vulkan_core.h'
    $glslang = Get-PinnedArchive 'glslang-16.6.0' `
        'https://github.com/KhronosGroup/glslang/releases/download/16.6.0/glslang-16.6.0-windows-x86_64-release.zip' `
        '82bf434e69b9bb4829de7e2b4bc2c5e7a7861e53d66cf75e5cc70f5f694a8d9b' `
        'bin\glslang.exe'
    $include = Join-Path $headers 'Vulkan-Headers-1.3.290\include'
    $compiler = Join-Path $glslang 'bin\glslang.exe'
}

& $compiler --version
if ($LASTEXITCODE -ne 0) {
    throw "Vulkan shader compiler failed: $compiler"
}
$cacheFile = Join-Path $CacheDirectory 'tools.cmake'
@"
# Generated by scripts/setup_vulkan_compute.ps1. Also refreshes an older CPU-only cache.
set(ORCA_VULKAN_INCLUDE_DIR [==[$($include.Replace('\', '/'))]==] CACHE PATH "Vulkan headers" FORCE)
set(ORCA_GLSLANG_VALIDATOR [==[$($compiler.Replace('\', '/'))]==] CACHE FILEPATH "Vulkan shader compiler" FORCE)
"@ | Set-Content -LiteralPath $cacheFile -Encoding UTF8
Write-Host "Vulkan build tools ready: $cacheFile"
