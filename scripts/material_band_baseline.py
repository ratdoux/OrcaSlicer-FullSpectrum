#!/usr/bin/env python3
"""Capture/compare the Catch2 production fixtures without changing G-code order.

Use a freshly built pinned-baseline libslic3r for the first capture. A source
revision alone is not proof of binary provenance; retain the configure/build
logs with the output. Each case runs in a separate process with two TBB threads.
"""

import argparse
import ctypes
import gzip
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import time


CASES = ("OFF-solid", "OFF-painted", "OFF-tapered")


def digest(data):
    return hashlib.sha256(data).hexdigest()


def normalize_gcode(data):
    # Only the timestamp and runtime object IDs in these known comments vary.
    # Keep every command, Z/E value, tool change, other comment and line order.
    text = data.decode("utf-8").replace("\r\n", "\n")
    text = re.sub(r"(?m)^(; generated by .+ on ).+$", r"\1<TIMESTAMP>", text)
    text = re.sub(r"(?m)^(; (?:(?:start|stop) )?printing object .+ id:)\d+( copy \d+)$", r"\1<ID>\2", text)
    return text.encode("utf-8")


def peak_working_set(process):
    if os.name != "nt":
        return None  # Do not mislabel a process-tree or sampled RSS as peak RSS.
    from ctypes import wintypes

    class Counters(ctypes.Structure):
        _fields_ = [("cb", wintypes.DWORD), ("PageFaultCount", wintypes.DWORD)] + [
            (name, ctypes.c_size_t) for name in (
                "PeakWorkingSetSize", "WorkingSetSize", "QuotaPeakPagedPoolUsage",
                "QuotaPagedPoolUsage", "QuotaPeakNonPagedPoolUsage", "QuotaNonPagedPoolUsage",
                "PagefileUsage", "PeakPagefileUsage")]
    counters = Counters()
    counters.cb = ctypes.sizeof(counters)
    get_memory = ctypes.windll.psapi.GetProcessMemoryInfo
    get_memory.argtypes = [wintypes.HANDLE, ctypes.POINTER(Counters), wintypes.DWORD]
    get_memory.restype = wintypes.BOOL
    if not get_memory(int(process._handle), ctypes.byref(counters), counters.cb):
        raise ctypes.WinError()
    return counters.PeakWorkingSetSize


def capture(executable, output, case, family="bbl"):
    output.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ, MATERIAL_BAND_BASELINE_DIR=str(output), MATERIAL_BAND_BASELINE_CASE=case,
               MATERIAL_BAND_BASELINE_FAMILY=family)
    command = [str(executable), "[material_band][baseline]", "--rng-seed", "20261026", "--warn", "NoAssertions"]
    started = time.perf_counter()
    with (output / "test.log").open("wb") as log:
        process = subprocess.Popen(command, stdout=log, stderr=subprocess.STDOUT, env=env)
        try:
            code = process.wait(timeout=300)
        except subprocess.TimeoutExpired:
            process.kill()
            process.wait()
            raise RuntimeError(f"{case} timed out; see {output / 'test.log'}") from None
        peak = peak_working_set(process)
    if code:
        raise RuntimeError(f"{case} failed ({code}); see {output / 'test.log'}")
    metrics = json.loads((output / "metrics.json").read_text())
    raw = (output / "output.gcode").read_bytes()
    normalized = normalize_gcode(raw)
    metrics.update(peak_working_set_bytes=peak, wall_seconds=time.perf_counter() - started,
                   profile_sha256=digest((output / "profile.json").read_bytes()),
                   normalized_gcode_sha256=digest(normalized), gcode_bytes=len(normalized),
                   tool_sequence=re.findall(r"(?m)^T\d+(?:\s*;.*)?$", normalized.decode("utf-8")))
    with (output / "normalized.gcode.gz").open("wb") as stream:
        with gzip.GzipFile(filename="", mode="wb", fileobj=stream, mtime=0) as compressed:
            compressed.write(normalized)
    (output / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\n")
    return metrics


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--test-exe", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--reference", type=Path)
    parser.add_argument("--runs", type=int, default=1, help="Cold processes per case; use >=5 for timing medians")
    args = parser.parse_args()
    if args.runs < 1:
        parser.error("--runs must be positive")
    executable, output = args.test_exe.resolve(), args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    results = {}
    for case in CASES:
        results[case] = []
        for run in range(args.runs):
            destination = output / case if args.runs == 1 else output / f"run-{run + 1}" / case
            metrics = capture(executable, destination, case)
            results[case].append(metrics)
            if args.reference:
                reference = args.reference / case
                expected = gzip.decompress((reference / "normalized.gcode.gz").read_bytes())
                actual = gzip.decompress((destination / "normalized.gcode.gz").read_bytes())
                if actual != expected:
                    raise RuntimeError(f"{case}: normalized G-code differs; compare {destination} and {reference}")
                old = json.loads((reference / "metrics.json").read_text())
                for key in ("profile_sha256", "layers", "slice_surfaces", "path_polylines", "path_segments",
                            "legacy_local_z_passes", "preview_moves", "tool_sequence"):
                    if old[key] != metrics[key]:
                        raise RuntimeError(f"{case}: {key} differs: {old[key]!r} != {metrics[key]!r}")
            print(f"{case} run {run + 1}: {metrics['normalized_gcode_sha256']}", flush=True)
    summary = {"binary_sha256": digest(executable.read_bytes()), "runs": results}
    (output / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")


if __name__ == "__main__":
    main()
