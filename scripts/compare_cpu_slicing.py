"""Compare runs from benchmark_cpu_slicing.py, including complete G-code output.

Only the generated-at timestamp is normalized. Motion, extrusion, ordering,
settings, comments and print estimates remain part of the comparison.
"""

import argparse
import datetime
import hashlib
import json
from pathlib import Path
import re
import statistics


GENERATED_AT = re.compile(rb"^(; generated by Snapmaker Orca .+) on \d{4}-\d\d-\d\d at \d\d:\d\d:\d\d(\r?\n)$")


def normalized_hash(path):
    digest = hashlib.sha256()
    normalized_lines = 0
    line_count = 0
    role = "Unspecified"
    role_digests = {}
    role_counts = {}
    print_statistics = []
    with path.open("rb") as stream:
        for line in stream:
            line_count += 1
            if line.startswith(b";TYPE:"):
                role = line[6:].strip().decode("utf-8")
            elif line.startswith((b"; filament used", b"; total filament used", b"; total filament cost",
                                  b"; estimated printing time")):
                print_statistics.append(line.strip().decode("utf-8"))
            elif (line.startswith((b"G1 ", b"G2 ", b"G3 ")) and b" E" in line
                  and any(axis in line for axis in (b" X", b" Y", b" Z"))):
                # Additional diagnostic only: this is not a replacement for full
                # comparison or a modal G-code/geometry equivalence validator.
                extrusion = line.split(b" E", 1)[1].split(b";", 1)[0].split()[0]
                if float(extrusion) > 0:
                    if role not in role_digests:
                        role_digests[role] = hashlib.sha256()
                    role_digests[role].update(line)
                    role_counts[role] = role_counts.get(role, 0) + 1
            line, count = GENERATED_AT.subn(rb"\1 on <timestamp>\2", line)
            normalized_lines += count
            digest.update(line)
    return {"sha256": digest.hexdigest(), "lines": line_count, "normalized_timestamps": normalized_lines,
            "positive_extrusion_commands_by_role": {
                role: {"sha256": value.hexdigest(), "commands": role_counts[role]} for role, value in role_digests.items()},
            "print_statistics": print_statistics}


def read_run(directory):
    metrics = json.loads((directory / "metrics.json").read_text(encoding="utf-8"))
    if metrics["exit_code"] != 0 or metrics["timed_out"] or not metrics["gcodes"]:
        raise ValueError(f"Run did not complete successfully: {directory}")
    stages = {}
    markers = {
        "slice_start": "Starting the slicing process.",
        "walls_start": "Generating walls...",
        "slice_end": "Slicing process finished.",
        "export_start": "Exporting G-code...",
        "export_end": "Exporting G-code finished",
    }
    log = (directory / "stdout.log").read_text(encoding="utf-8", errors="replace")
    for line in log.splitlines():
        for key, marker in markers.items():
            if marker in line and line.startswith("["):
                stages[key] = datetime.datetime.fromisoformat(line[1:line.index("]")])
    derived = {}
    for key, start, end in (("slice_seconds", "slice_start", "slice_end"),
                            ("mesh_paint_local_z_seconds", "slice_start", "walls_start"),
                            ("export_seconds", "export_start", "export_end")):
        if start in stages and end in stages:
            derived[key] = (stages[end] - stages[start]).total_seconds()
    diagnostics = list((directory / "data" / "SVG").glob("local-z-plan-*"))
    schedules = re.findall(r"Local-Z wipe tower dependency scheduler[^\r\n]+", log)
    return {
        "directory": str(directory), "project_sha256": metrics["project_sha256"],
        "dll_sha256": metrics["dll_sha256"],
        "wall_seconds": metrics["wall_seconds"], "cpu_seconds": metrics.get("cpu_seconds"),
        "peak_working_set_mib": metrics["peak_bytes"]["working_set"] / 2**20,
        "peak_commit_mib": metrics["peak_bytes"]["commit"] / 2**20,
        "diagnostic_files": len(diagnostics),
        "diagnostic_bytes": sum(p.stat().st_size for p in diagnostics),
        "local_z_schedule_count": len(schedules),
        "local_z_schedule_sha256": hashlib.sha256("\n".join(schedules).encode("utf-8")).hexdigest(),
        "local_z_warnings": {message: log.count(message) for message in (
            "preplanned wipe tower sequence mismatch", "toolchange reserve exhausted",
            "trailing wipe tower transition cannot be reconciled", "base clip leak",
            "local pass height mismatch", "no path passes")},
        **derived,
        "gcodes": {p["file"]: normalized_hash(directory / p["file"]) for p in metrics["gcodes"]},
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--before", type=Path, nargs="+", required=True)
    parser.add_argument("--after", type=Path, nargs="+", required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    groups = {"before": [read_run(p) for p in args.before], "after": [read_run(p) for p in args.after]}
    runs = groups["before"] + groups["after"]
    if len({r["project_sha256"] for r in runs}) != 1:
        parser.error("All runs must use exactly the same project.")
    for name, group in groups.items():
        if len({r["dll_sha256"] for r in group}) != 1:
            parser.error(f"Multiple builds in the {name} group.")
    reference = runs[0]["gcodes"]
    equal = all(r["gcodes"] == reference for r in runs)
    comparisons = {}
    for metric in ("wall_seconds", "cpu_seconds", "slice_seconds", "mesh_paint_local_z_seconds", "export_seconds",
                   "peak_working_set_mib", "peak_commit_mib"):
        if not all(r.get(metric) is not None for r in runs):
            continue
        values = {name: [r[metric] for r in group] for name, group in groups.items()}
        before, after = (statistics.median(values[name]) for name in ("before", "after"))
        comparisons[metric] = {
            "before_median": before, "after_median": after,
            "reduction_percent": 100 * (before - after) / before if before else None,
            **{f"{name}_range": [min(v), max(v)] for name, v in values.items()},
        }
    result = {"all_normalized_gcode_equal": equal,
              "all_local_z_warning_counts_equal": all(r["local_z_warnings"] == runs[0]["local_z_warnings"] for r in runs),
              "all_local_z_schedules_equal": all(r["local_z_schedule_sha256"] == runs[0]["local_z_schedule_sha256"] for r in runs),
              "comparisons": comparisons, "runs": groups}
    args.output.write_text(json.dumps(result, indent=2), encoding="utf-8")
    print(json.dumps({k: v for k, v in result.items() if k != "runs"}, indent=2))
    return 0 if equal else 1


if __name__ == "__main__":
    raise SystemExit(main())
